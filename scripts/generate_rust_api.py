"""Generate the Rust engine client from the checked-in v1 schemas."""

import argparse
import json
import re
import subprocess
from typing import cast

from contract_files import CONTRACT
from contract_files import ROOT
from contract_files import write_or_check

type Schema = dict[str, object]
type Schemas = dict[str, Schema]

HEADER = "// Generated by scripts/generate_rust_api.py; do not edit.\n"
OUTPUT = ROOT / "ngn/crates/ngn-api/src"
KEYWORDS = {"type", "match", "ref", "fn", "as", "move", "enum", "use", "async", "await", "dyn", "gen"}
HTTP_METHODS = {"get", "post", "put", "delete", "patch", "head", "options", "trace"}


def record(value: object) -> Schema:
    if not isinstance(value, dict) or not all(isinstance(key, str) for key in value):
        raise ValueError(f"Expected a schema object, got {value!r}")
    return cast("Schema", value)


def items(value: object) -> list[object]:
    if not isinstance(value, list):
        raise ValueError(f"Expected a schema list, got {value!r}")
    return cast("list[object]", value)


def text(value: object) -> str:
    if not isinstance(value, str):
        raise ValueError(f"Expected schema text, got {value!r}")
    return value


def component(reference: object) -> str:
    return text(reference).rsplit("/", 1)[1]


def variant(value: str) -> str:
    return "".join(word.capitalize() for word in re.split(r"[^A-Za-z0-9]+", value))


def literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def alternatives(schema: Schema) -> tuple[Schema, bool]:
    if "anyOf" not in schema:
        return schema, False
    variants = [record(value) for value in items(schema["anyOf"])]
    nonnull = [value for value in variants if value.get("type") != "null"]
    if len(nonnull) == 1 and len(variants) == 2:
        return nonnull[0], True
    raise ValueError(f"Unsupported anonymous union: {schema}")


def rust_type(schema: Schema) -> str:
    shape, nullable = alternatives(schema)
    if "$ref" in shape:
        result = component(shape["$ref"])
    elif shape.get("type") == "array":
        result = f"Vec<{rust_type(record(shape['items']))}>"
    elif shape.get("type") == "object" and isinstance(shape.get("additionalProperties"), dict):
        result = f"std::collections::BTreeMap<String, {rust_type(record(shape['additionalProperties']))}>"
    elif shape.get("type") == "integer":
        minimum = shape.get("minimum", shape.get("const"))
        result = "u64" if isinstance(minimum, int) and minimum >= 0 else "i64"
    else:
        kinds = {"string": "String", "boolean": "bool", "number": "f64", "object": "serde_json::Value"}
        if (kind := shape.get("type")) not in kinds:
            raise ValueError(f"Unsupported field schema: {schema}")
        result = kinds[text(kind)]
    return f"Option<{result}>" if nullable else result


def structure(name: str, schema: Schema, *, tag: str = "") -> str:
    fields = record(schema.get("properties", {}))
    required = set(items(schema.get("required", [])))
    lines = ["#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]"]
    if schema.get("additionalProperties") is False:
        lines.append("#[serde(deny_unknown_fields)]")
    lines.append(f"pub struct {name} {{")
    for field, raw in fields.items():
        if field == tag:
            continue
        shape, nullable = alternatives(record(raw))
        kind = rust_type(shape)
        if "const" in shape:
            constant = shape["const"]
            if type(constant) is not int or kind != "u64" or field not in required:
                raise ValueError(f"Unsupported constant field: {name}.{field} = {constant!r}")
            lines.append(f'#[serde(deserialize_with = "const_u64::<_, {constant}>")]')
        elif field not in required:
            if nullable:
                lines.append(
                    '#[serde(default, deserialize_with = "optional_nullable", skip_serializing_if = "Option::is_none")]'
                )
                kind = f"Option<Option<{kind}>>"
            else:
                lines.append(
                    '#[serde(default, deserialize_with = "optional_value", skip_serializing_if = "Option::is_none")]'
                )
                kind = f"Option<{kind}>"
        elif nullable:
            # An ordinary serde Option accepts a missing field, even if the
            # contract says the field is required with a nullable value.
            lines.append('#[serde(deserialize_with = "required_nullable")]')
            kind = f"Option<{kind}>"
        rust_field = f"r#{field}" if field in KEYWORDS else field
        lines.append(f"pub {rust_field}: {kind},")
    return "\n".join([*lines, "}"])


def string_enum(name: str, schema: Schema) -> str:
    values = [(variant(text(value)), literal(text(value))) for value in items(schema["enum"])]
    cases = [case for case, _ in values]
    if len(set(cases)) != len(cases) or "Unknown" in cases:
        raise ValueError(f"Non-unique Rust enum cases: {name}")
    encode = "\n".join(f"Self::{case} => {wire}," for case, wire in values)
    decode = "\n".join(f"{wire} => Self::{case}," for case, wire in values)
    names = ", ".join([*cases, "Unknown(String)"])
    return f"""
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum {name} {{ {names} }}

impl {name} {{
    pub fn as_str(&self) -> &str {{
        match self {{
            {encode}
            Self::Unknown(value) => value,
        }}
    }}
}}

impl Serialize for {name} {{
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {{
        serializer.serialize_str(self.as_str())
    }}
}}

impl<'de> Deserialize<'de> for {name} {{
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{
        let value = String::deserialize(deserializer)?;
        Ok(match value.as_str() {{
            {decode}
            _ => Self::Unknown(value),
        }})
    }}
}}
""".strip()


def discriminator(schema: Schema) -> tuple[str, dict[str, str]]:
    value = record(schema["discriminator"])
    return text(value["propertyName"]), {tag: component(ref) for tag, ref in record(value["mapping"]).items()}


def tagged_union(name: str, tag: str, choices: dict[str, str]) -> str:
    variants = "\n".join(f"{child}({child})," for child in choices.values())
    encode = "\n".join(
        f"Self::{child}(body) => ({literal(wire)}, serde_json::to_value(body).map_err(serde::ser::Error::custom)?),"
        for wire, child in choices.items()
    )
    decode = "\n".join(
        f"{literal(wire)} => serde_json::from_value(body).map(Self::{child}).map_err(serde::de::Error::custom),"
        for wire, child in choices.items()
    )
    field = literal(tag)
    return f"""
#[derive(Clone, Debug, PartialEq)]
pub enum {name} {{
    {variants}
    Unknown(String, serde_json::Value),
}}

impl Serialize for {name} {{
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {{
        let (tag, mut body) = match self {{
            {encode}
            Self::Unknown(tag, raw) => (tag.as_str(), raw.clone()),
        }};
        body.as_object_mut()
            .ok_or_else(|| serde::ser::Error::custom("event payload must be an object"))?
            .insert({field}.into(), serde_json::Value::String(tag.into()));
        body.serialize(serializer)
    }}
}}

impl<'de> Deserialize<'de> for {name} {{
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {{
        let body = serde_json::Value::deserialize(deserializer)?;
        let tag = body.get({field}).and_then(serde_json::Value::as_str)
            .ok_or_else(|| serde::de::Error::custom("event discriminator must be a string"))?
            .to_owned();
        match tag.as_str() {{
            {decode}
            _ => Ok(Self::Unknown(tag, body)),
        }}
    }}
}}
""".strip()


def models(schemas: Schemas, *, version: int, revision: int, event_path: str, subprotocol: str) -> str:
    unions = {name: discriminator(schema) for name, schema in schemas.items() if "discriminator" in schema}
    tags = {variant_name: tag for tag, choices in unions.values() for variant_name in choices.values()}
    sections = [
        HEADER,
        "use serde::{Deserialize, Deserializer, Serialize};",
        f"pub const PROTOCOL_VERSION: u64 = {version};",
        f"pub const PROTOCOL_REVISION: u64 = {revision};",
        f"pub const EVENTS_PATH: &str = {literal(event_path)};",
        f"pub const EVENTS_SUBPROTOCOL: &str = {literal(subprotocol)};",
        """
fn optional_nullable<'de, D, T>(value: D) -> Result<Option<Option<T>>, D::Error>
where D: Deserializer<'de>, T: Deserialize<'de> {
    Option::<T>::deserialize(value).map(Some)
}

fn optional_value<'de, D, T>(value: D) -> Result<Option<T>, D::Error>
where D: Deserializer<'de>, T: Deserialize<'de> {
    T::deserialize(value).map(Some)
}

fn required_nullable<'de, D, T>(value: D) -> Result<Option<T>, D::Error>
where D: Deserializer<'de>, T: Deserialize<'de> {
    Option::<T>::deserialize(value)
}

fn const_u64<'de, D: Deserializer<'de>, const EXPECTED: u64>(value: D) -> Result<u64, D::Error> {
    let seen = u64::deserialize(value)?;
    if seen != EXPECTED {
        return Err(serde::de::Error::custom(format!("expected {EXPECTED}, got {seen}")));
    }
    Ok(seen)
}
""".strip(),
    ]
    for name, schema in sorted(schemas.items()):
        if name in unions:
            sections.append(tagged_union(name, *unions[name]))
        elif name == "JsonValue" and not schema:
            sections.append("pub type JsonValue = serde_json::Value;")
        elif "enum" in schema:
            sections.append(string_enum(name, schema))
        elif schema.get("type") == "object" and "properties" in schema:
            sections.append(structure(name, schema, tag=tags.get(name, "")))
        else:
            sections.append(f"pub type {name} = {rust_type(schema)};")
    return "\n\n".join(sections) + "\n"


def json_shape(body: object) -> Schema:
    content = record(record(body)["content"])
    return record(record(content["application/json"])["schema"])


def operation(path: str, verb: str, metadata: Schema) -> str:
    name = text(metadata["operationId"])
    (response,) = [value for status, value in record(metadata["responses"]).items() if status.startswith("2")]
    result = rust_type(json_shape(response))
    signature = []
    path_names = set()
    query = []
    for item in items(metadata.get("parameters", [])):
        parameter = record(item)
        key = text(parameter["name"])
        where = text(parameter["in"])
        if where == "path":
            signature.append(f"{key}: &str")
            path_names.add(key)
        elif where == "query":
            signature.append(f"{key}: {rust_type(record(parameter['schema']))}")
            query.append(f"({literal(key)}, {key}.to_string())")
        else:
            raise ValueError(f"Unsupported parameter: {parameter}")
    segments = []
    for segment in path.strip("/").split("/"):
        if (value := segment.removeprefix("{").removesuffix("}")) in path_names:
            segments.append(value)
        else:
            segments.append(literal(segment))
    body_type = "()"
    body = "None"
    if "requestBody" in metadata:
        body_type = rust_type(json_shape(metadata["requestBody"]))
        signature.append(f"body: &{body_type}")
        body = "Some(body)"
    return f"""
pub async fn {name}(&self, {", ".join(signature)}) -> Result<{result}, Error> {{
    self.send::<{result}, {body_type}>(
        Method::{verb.upper()}, &[{", ".join(segments)}], &[{", ".join(query)}], {body}
    ).await
}}
""".strip()


def client(paths: Schema) -> str:
    operations = [
        operation(path, verb, record(metadata))
        for path, item in paths.items()
        for verb, metadata in record(item).items()
        if verb in HTTP_METHODS
    ]
    return (
        HEADER
        + "\nuse reqwest::Method;\nuse crate::{Client, Error, models::*};\nimpl Client {\n"
        + ("\n\n".join(operations))
        + "\n}\n"
    )


def rustfmt(source: str) -> str:
    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=source,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail rather than writing stale files.")
    arguments = parser.parse_args()
    api = record(json.loads((CONTRACT / "openapi.json").read_text(encoding="utf-8")))
    events = record(json.loads((CONTRACT / "events.schema.json").read_text(encoding="utf-8")))
    engine_version = text(record(api["info"])["version"]).split(".")
    event_spec = record(api["x-ngn-events"])
    components = record(record(api["components"])["schemas"])
    # HTTP validation errors are framework responses, never successful method
    # results. Event definitions are authoritative in their standalone schema.
    schemas = {
        name: record(item)
        for name, item in components.items()
        if name not in {"ValidationError", "HTTPValidationError"}
    }
    schemas.update({name: record(item) for name, item in record(events["$defs"]).items()})
    schemas["EventRecord"] = {key: value for key, value in events.items() if key not in {"$defs", "$schema"}}
    output = {
        "models.rs": models(
            schemas,
            version=int(engine_version[0]),
            revision=int(engine_version[1]),
            event_path=text(event_spec["path"]),
            subprotocol=text(event_spec["subprotocol"]),
        ),
        "methods.rs": client(record(api["paths"])),
    }
    results = [write_or_check(OUTPUT / name, rustfmt(source), check=arguments.check) for name, source in output.items()]
    if not all(results):
        print("Run python scripts/generate_rust_api.py.")
        return 1
    print("Generated ngn-api types and HTTP methods are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
